import './globals.css';

import { appConfig } from '@app/[locale]/config';
import { AlertProvider, ThemeProvider } from '@core/context';
import type { LayoutProps } from '@core/types';
import { redirect } from '@i18n/routing';
import type { Metadata } from 'next';
import { Inter } from 'next/font/google';
import { NextIntlClientProvider } from 'next-intl';
import React from 'react';

const inter = Inter({
  variable: '--font-inter',
  subsets: ['latin', 'cyrillic'],
  display: 'swap',
});

export const metadata: Metadata = {
  title: 'LinkUp Chat',
  description: 'Generated by create next app',
};

export default async function RootLayout({ children, params }: LayoutProps) {
  const { locale: urlLocale } = await params;
  const { theme, dbLocale, messages } = await appConfig(urlLocale);

  if (dbLocale !== urlLocale) {
    redirect({
      href: {
        pathname: '/',
      },
      locale: dbLocale,
    });
  }

  return (
    <html lang={dbLocale} suppressHydrationWarning className={theme}>
      <body
        data-component="root-layout"
        className={`${inter.variable} bg-main-bg font-sans antialiased`}
      >
        <NextIntlClientProvider
          locale={dbLocale}
          key={dbLocale}
          messages={messages}
        >
          <ThemeProvider key={theme} initialTheme={theme}>
            <AlertProvider>{children}</AlertProvider>
          </ThemeProvider>
        </NextIntlClientProvider>
      </body>
    </html>
  );
}
